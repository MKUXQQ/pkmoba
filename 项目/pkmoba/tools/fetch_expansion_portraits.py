"""Fetch the eight real expansion-species portraits into 64x64 framed PNGs.

Rules:
  * always use an official illustration of the species (no procedural substitute);
  * keep the whole silhouette (crop to alpha bbox, pad to square, LANCZOS 64px);
  * record the URL actually used in textures/gui/pokemon/EXPANSION-SOURCE.md;
  * fail loudly (non-zero exit, no file written) when every mirror is unreachable,
    so a broken network can never silently ship a placeholder portrait.

Run:  python tools/fetch_expansion_portraits.py
"""

from __future__ import annotations

import io
import sys
import time
import urllib.request
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_pokemon_portraits import frame  # noqa: E402  (same 64x64 frame style)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/main/resources/assets/pkmoba/textures/gui/pokemon"

SIZE = 64
ATTEMPTS = 3
BACKOFF = 2.0
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) PKMOBA-portrait-fetch/1.0"

# species id -> (national dex, Chinese name, English name)
SPECIES = {
    "lucario": (448, "路卡利欧", "Lucario"),
    "abomasnow": (460, "暴雪王", "Abomasnow"),
    "blaziken": (257, "火焰鸡", "Blaziken"),
    "gengar": (94, "耿鬼", "Gengar"),
    "tyranitar": (248, "班基拉斯", "Tyranitar"),
    "garchomp": (445, "烈咬陆鲨", "Garchomp"),
    "scizor": (212, "巨钳螳螂", "Scizor"),
    "gardevoir": (282, "沙奈朵", "Gardevoir"),
}


def mirrors(dex: int) -> list[tuple[str, str]]:
    """Official-art mirrors, most faithful artwork first. All return transparent PNG."""
    return [
        ("PokeAPI official-artwork",
         f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/{dex}.png"),
        ("PokeAPI HOME render",
         f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/home/{dex}.png"),
        ("pokemon.com Pokédex",
         f"https://assets.pokemon.com/assets/cms2/img/pokedex/full/{dex:03d}.png"),
    ]


def download(url: str) -> bytes | None:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(1, ATTEMPTS + 1):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return resp.read()
        except Exception as exc:  # noqa: BLE001 - mirrors fail with many socket errors
            print(f"    attempt {attempt}/{ATTEMPTS} {type(exc).__name__}: {str(exc)[:90]}")
            time.sleep(BACKOFF * attempt)
    return None


def cut_whole_silhouette(raw: Image.Image) -> Image.Image:
    """Crop to the alpha bounding box, pad to a square, resize to 64x64."""
    img = raw.convert("RGBA")
    alpha = img.getchannel("A")
    lo, hi = alpha.getextrema()
    if hi == 0 or lo == 255:
        raise ValueError("image has no transparent pixels (looks like a white-background scan)")
    box = img.getbbox()
    if not box:
        raise ValueError("empty alpha bbox")
    img = img.crop(box)
    side = max(img.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.alpha_composite(img, ((side - img.width) // 2, (side - img.height) // 2))
    return square.resize((SIZE, SIZE), Image.Resampling.LANCZOS)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    rows: list[tuple[str, str, str, str]] = []
    missing: list[str] = []

    for name, (dex, zh, en) in SPECIES.items():
        print(f"{name} ({zh} / {en}, #{dex})")
        used_url = ""
        used_src = ""
        for source, url in mirrors(dex):
            print(f"  source: {source}")
            data = download(url)
            if not data:
                continue
            try:
                raw = Image.open(io.BytesIO(data))
                portrait = cut_whole_silhouette(raw)
            except Exception as exc:  # noqa: BLE001
                print(f"    rejected image: {exc}")
                continue
            target = OUT / f"{name}.png"
            frame(portrait).save(target)
            used_url, used_src = url, source
            with Image.open(target) as written:
                print(f"    OK {len(data)} bytes -> {name}.png ({written.size[0]}x{written.size[1]} {written.mode})")
            break
        if used_url:
            rows.append((name, zh, used_src, used_url))
        else:
            missing.append(name)
            print(f"    FAILED: no mirror returned a usable image for {name}")

    lines = [
        "# Expansion portrait provenance",
        "",
        "64x64 PNGs generated by `tools/fetch_expansion_portraits.py`: whole silhouette cropped to the",
        "alpha bounding box, padded to a square, LANCZOS-resized to 64px, then framed with the shared",
        "beige/brown UI border (same as the four launch species). No repainting, no procedural faces.",
        "",
        f"Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "Original Pokémon illustrations: Pokémon / Nintendo / Creatures / GAME FREAK.",
        "Distribution inside this mod does not grant a license to the original artwork.",
        "",
        "| species | 中文 | mirror | URL |",
        "| --- | --- | --- | --- |",
    ]
    for name, zh, src, url in rows:
        lines.append(f"| {name} | {zh} | {src} | {url} |")
    if missing:
        lines += ["", f"MISSING (network failure, rerun the script): {', '.join(missing)}"]
    (OUT / "EXPANSION-SOURCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    if missing:
        print("ERROR: missing real portraits: " + ", ".join(missing))
        return 1
    print(f"done: {len(rows)}/8 portraits in {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
