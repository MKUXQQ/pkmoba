package com.pkmoba.client;

import net.minecraft.world.phys.Vec3;
import net.minecraft.util.RandomSource;

/**
 * 「大」字采样蒙版（加粗版：笔宽 0.14，撇捺末端 0.06）。
 *
 * <p>四笔都是"沿路径扫圆盘"生成的圆形端点，所以边缘是椭圆的，没有针尖。
 * 这个 32×32 蒙版从同一张贴图导出，冒火点严格落在笔画上。
 */
public final class GlyphGeometry {
    private static final String[] MASK = {
            "00000000000000011000000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00000000000000111100000000000000",
            "00001111111111111111111111110000",
            "00011111111111111111111111111000",
            "00011111111111111111111111111000",
            "00011111111111111111111111111000",
            "00011111111111111111111111111000",
            "00000000000111111111100000000000",
            "00000000000111111111100000000000",
            "00000000001111100111110000000000",
            "00000000011111000011111000000000",
            "00000000111110000001111100000000",
            "00000001111100000000111110000000",
            "00000011111000000000011111000000",
            "00000011110000000000001111000000",
            "00000111100000000000000111100000",
            "00001111000000000000000011110000",
            "00011110000000000000000001111000",
            "00111100000000000000000000111100",
            "01110000000000000000000000001110",
            "00100000000000000000000000000100",
            "00000000000000000000000000000000",
            "00000000000000000000000000000000",
    };

    private static final int N = 32;

    private GlyphGeometry() {
    }

    public static Vec3 randomPoint(RandomSource rnd) {
        for (int attempt = 0; attempt < 32; attempt++) {
            int x = rnd.nextInt(N);
            int y = rnd.nextInt(N);
            if (MASK[y].charAt(x) != '1') {
                continue;
            }
            double ux = (x + 0.5) / N - 0.5;
            double uy = 0.5 - (y + 0.5) / N;
            double len = Math.sqrt(ux * ux + uy * uy);
            if (len > 1.0E-4) {
                double out = rnd.nextDouble() * 0.03;
                ux += ux / len * out;
                uy += uy / len * out;
            }
            return new Vec3(ux, uy, 0);
        }
        return Vec3.ZERO;
    }
}
